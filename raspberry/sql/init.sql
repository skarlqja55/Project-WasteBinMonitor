-- Reproduction schema derived from the C, PHP and Python queries.
CREATE DATABASE IF NOT EXISTS iotdb CHARACTER SET utf8mb4;
USE iotdb;

CREATE TABLE IF NOT EXISTS food_bin (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    bin_a SMALLINT NOT NULL,
    bin_b SMALLINT NOT NULL,
    bin_c SMALLINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS collection_history (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    bin_name CHAR(1) NOT NULL,
    collected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS request_history (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    bin_name CHAR(1) NOT NULL,
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
